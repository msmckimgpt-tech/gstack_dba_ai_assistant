"""연결·하트비트 타이밍 상수.

본 모듈은 `bridge_agent.py` 단일 파일 러너의 **소스 조각**이다 — 배포 산출물은
`bin/build-bridge-agent.py` 가 이 패키지를 결정적 순서로 연접해 만든다.
"""
from __future__ import annotations

import os

#: 연결이 **끊겼을 때만** 쓰는 복구 간격(feature-0045). 서버가 배포로 교체되는 몇 초 동안
#: 연결이 실패하는데, 그때 쉬지 않고 재시도하면 초당 수천 번을 두드려 사용자 머신의 CPU 를
#: 태운다. 대기(`wait_for_request`)에는 여전히 sleep 이 없다 — 이건 대기가 아니라 재연결이다.
#: 상한을 15초로 둔 이유: 롤링 배포 한 replica 의 교체가 보통 그 안에 끝나므로, 복구가
#: 지연되어 질문 인지가 늦어지는 일이 없다.
_RECONNECT_BACKOFF_START = 1.0
_RECONNECT_BACKOFF_MAX = 15.0

#: 서버가 "배포 교대 중" 이라고 답했을 때의 **하한**. 백오프가 아니라 고정값이다 — 자라지
#: 않으므로 인지가 늦어지지 않고, 엣지가 그 인스턴스를 후보에서 빼는 짧은 창(2s)에 호출이
#: 폭주해 계정 호출 상한을 태우는 것만 막는다.
_DRAINING_RETRY_FLOOR_SEC = 0.5

#: 하트비트 주기의 **기본값**(TASK-20260828T150000). 실제 값은 서버가 첫 응답으로 알려주고
#: 그 뒤로는 그것을 쓴다 — 클라이언트가 각자 정하면 서버의 판정 창이 사람마다 다른 의미가
#: 된다(P0-J 의 '환경 차이 금지' 와 같은 축). 여기 값은 서버 응답을 받기 전까지의 임시값이다.
_HEARTBEAT_INTERVAL_SEC = 30.0
#: 하트비트 호출의 응답 대기 상한. 이건 대기가 아니라 **짧은 신호**라 길게 잡을 이유가 없다.
_HEARTBEAT_TIMEOUT_SEC = 15.0
#: 서버가 알려준 주기의 **하한**. 서버가 0 이나 음수를 주는 사고에도 신호가 폭주하지 않게.
#: (상한은 두지 않는다 — 판정 창을 정하는 쪽이 서버이므로 길게 주는 것은 서버의 선택이다.)
_HEARTBEAT_MIN_INTERVAL_SEC = 5.0

#: 배경 능력 협상이 **서버 baseline 을 기다리는 상한** (TASK-20260902T140200).
#:
#: baseline 은 하트비트 첫 응답으로 온다. 협상이 그것을 기다리지 않으면 거의 항상 먼저
#: 출발해 확인 경로가 **사실상 발화하지 않고**, 그러면 목록 안정화가 코드로만 존재한다
#: (§16.7 G14-e: 존재는 실행이 아니다).
#:
#: 값의 근거: 하트비트 1회의 응답 상한이 `_HEARTBEAT_TIMEOUT_SEC`(15초)이므로, 첫 신호가
#: 성공하든 실패하든 그 안에 결론이 난다. 상한을 그보다 짧게 잡으면 정상적인 첫 응답을
#: 기다리지 못하고(느린 링크에서 확인 경로를 놓친다), 길게 잡으면 서버가 응답하지 않을 때
#: 웹 선택기의 공백이 그만큼 길어진다 — 이 cycle 이 줄이려는 바로 그 공백이다.
#: 그래서 «첫 응답이 결론 나는 시간» 에 여유 1초를 더한 값으로 고정한다.
_CAPS_BASELINE_WAIT_SEC = _HEARTBEAT_TIMEOUT_SEC + 1.0

#: 능력 협상이 **아무것도 얻지 못했을 때** 다시 물어보는 간격 사다리(초).
#:
#: ## 왜 재시도가 필요한가 (사용자 제보 2026-09-07)
#:
#: 종전 협상은 기동 시 **1회**였다. 그 1회가 실패하면 그 러너가 사는 동안 웹 선택기는
#: 영영 비어 있는다 — 그런데 서버가 그 자리에 내보내는 문구는 「확인하는 중입니다」다.
#: 즉 화면은 진행 중이라고 말하는데 실제로는 아무것도 다시 확인하지 않았다.
#:
#: 실패는 **일시적인 쪽이 흔하다**: 이 파일이 이미 기록한 실측대로 codex 는 「같은 조건에서
#: 성공(6종 응답)과 실패를 오간다」이고, 라이브에서 관측된 사유는 `OAuth access token has
#: expired`(로그인하면 풀린다) · `TimeoutExpired`(그때 그 머신이 느렸다) 였다. 셋 다 다시
#: 물으면 풀리는 종류인데, 다시 묻는 코드가 없었다.
#:
#: ## 값의 근거 (경계 양측 — §16.7 G4)
#:
#: - 첫 간격 60초: 사용자가 화면을 보고 있는 시간 안에 한 번은 다시 시도된다. 이보다 짧으면
#:   기동 직후 연달아 두 번 물어 그 AI 의 토큰을 겹쳐 태운다(협상 1회 = 실측 codex 10~25초).
#: - 사다리(60→120→300→600)와 천장(900초): 「고칠 수 있는 원인」은 대개 몇 분 안에 고쳐지고,
#:   고쳐지지 않는 원인은 15분에 한 번이면 충분하다. 시간당 최대 4회 · 회당 수십 초라
#:   개인 계정 비용이 무시할 수준으로 남는다.
#: - **상한을 두지 않는다**: 총 횟수를 정해 멈추면 「한 시간 뒤에 로그인을 고친 사용자」가
#:   목록을 영영 못 받는다 — 그것이 이 재시도가 없애려는 상태와 정확히 같은 상태다.
#:
#: 성공하면 그 자리에서 멈춘다(얻은 목록은 캐시되어 다음 회차에 다시 묻지 않는다).
_CAPS_RETRY_BACKOFF_SEC = (60.0, 120.0, 300.0, 600.0)
_CAPS_RETRY_CEILING_SEC = 900.0

#: **화면에 이미 보여줄 목록이 있을 때**의 천장 (security 적대리뷰 P2, 2026-09-07).
#:
#: 원장 폴백(`baseline`)이 서면 사용자는 목록을 본다 — 막혀 있지 않다. 그런데도 재시도는
#: 계속 돈다(폴백은 확인된 값이 아니므로). 그 상태에서 15분 천장을 그대로 쓰면 회차마다
#: 확인질의(≤60초) + 열린질의 2회(≤240초 deadline)를 사용자 **개인 계정 토큰**으로 태운다 —
#: 위 주석의 「회당 수십 초」는 그 경로에서 참이 아니다(같은 cycle 이 기록한 실측: 열린질의
#: 22.7초~타임아웃, 확인질의 600초 타임아웃).
#:
#: 그래서 축을 둘로 가른다: **아무것도 못 보여주는 동안**은 위 사다리로 빠르게 되묻고,
#: **보여줄 것이 생긴 뒤**로는 1시간에 한 번만 «진짜 답» 을 노린다. 사용자가 막혀 있지
#: 않으므로 서두를 이유가 없고, 그렇다고 멈추지도 않는다(폴백은 결론이 아니다).
_CAPS_RETRY_CEILING_SHOWING_SEC = 3600.0
#: 하트비트가 주기 대기 중 「지금 신고해라」(`nudge`) 와 종료(`stop`) 를 함께 살피는 간격.
#:
#: 두 이벤트를 동시에 기다리는 표준 수단이 없어 짧게 쪼개 번갈아 본다. 값의 근거(경계
#: 양측 — §16.7 G4): 이보다 크면 종료가 그만큼 늦어지고(최악 = 이 값), 이보다 작으면
#: 아무 일도 없는 30초 주기마다 깨어나는 횟수만 는다. 0.5초면 사람이 못 느끼고
#: 주기당 60회라 비용도 없다.
_HEARTBEAT_NUDGE_POLL_SEC = 0.5


#: 연결이 해제된 뒤(로그아웃) **진행 중 작업을 기다리는 유예**. 이 시간이 지나면 중단하고
#: 종료한다. 짧게 잡은 이유: 그 답변들은 이미 전달될 곳이 없고(토큰 무효 → 제출 401), 오래
#: 붙잡을수록 아무도 볼 수 없는 답을 위해 개인 계정 토큰만 탄다. 그래도 0 이 아닌 이유는
#: **곧 끝날 일을 중간에 끊지 않기** 위해서다.
_SHUTDOWN_GRACE_SEC = float(os.environ.get("BRIDGE_SHUTDOWN_GRACE_SEC", "") or 120.0)
